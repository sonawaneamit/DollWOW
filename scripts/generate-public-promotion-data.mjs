import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const pick = (value, keys) => Object.fromEntries(keys.filter(key => value[key] !== undefined).map(key => [key, value[key]]));
const campaignKeys = ['startsOn', 'endsOn', 'cashDiscountOnOrder'];
const lightweightKeys = ['bodies', 'supplierSurchargeUSD', 'suggestedMinimumRetailSurchargeUSD', 'siliconeHeadRetailSurchargeUSD', 'combinedRetailSurchargeUSD', 'upgradesChargedSeparately', 'octoberUpgradeDiscountPercent', 'octoberSupplierSurchargeUSD', 'octoberRetailSurchargeUSD', 'octoberCombinedRetailSurchargeUSD', 'chargeReady'];

// Generate a separate import target: runtime stripping cannot remove evidence from a JS bundle.
export function publicPromotionOutputs() {
  const source = ts.createSourceFile('october2026Draft.ts', read('lib/promotions/october2026Draft.ts'), ts.ScriptTarget.Latest, true);
  const filterObject = (node, keys) => ts.factory.updateObjectLiteralExpression(node,
    node.properties.filter(property => property.name && keys.includes(property.name.getText(source).replace(/['"]/g, ''))));
  const result = ts.transform(source, [context => {
    const visit = node => {
      if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && node.initializer && ts.isAsExpression(node.initializer)) {
        let object = node.initializer.expression;
        if (ts.isObjectLiteralExpression(object) && node.name.text === 'OCTOBER_CAMPAIGNS') {
          object = ts.factory.updateObjectLiteralExpression(object, object.properties.map(property =>
            ts.isPropertyAssignment(property) && ts.isObjectLiteralExpression(property.initializer)
              ? ts.factory.updatePropertyAssignment(property, property.name, filterObject(property.initializer, campaignKeys)) : property));
        } else if (ts.isObjectLiteralExpression(object) && node.name.text === 'SE_LIGHTWEIGHT_DRAFT') {
          object = filterObject(object, lightweightKeys);
        }
        return ts.factory.updateVariableDeclaration(node, node.name, node.exclamationToken, node.type,
          ts.factory.updateAsExpression(node.initializer, object, node.initializer.type));
      }
      return ts.visitEachChild(node, visit, context);
    };
    return node => ts.visitNode(node, visit);
  }]);
  const runtime = '// Generated by scripts/generate-public-promotion-data.mjs. Do not edit.\n'
    + ts.createPrinter({ removeComments: true }).printFile(result.transformed[0]);
  result.dispose();
  const reviewed = JSON.parse(read('data/promotions/se-october-2026-reviewed.json'));
  const publicReviewed = {
    paid: Object.fromEntries(Object.entries(reviewed.paid).map(([handle, rows]) => [handle, rows.map(row => pick(row,
      ['groupId', 'groupLabel', 'optionId', 'label', 'catalog', 'promo']))])),
    lightweight: reviewed.lightweight
  };
  const library = JSON.parse(read('data/promotions/se-silicone-head-library.json'));
  const publicHeads = { heads: library.heads.map(head => ({
    ...pick(head, ['id', 'label', 'ros']),
    imagePath: new URL(head.image).pathname
  })) };
  return {
    'lib/promotions/october2026Runtime.ts': runtime,
    'data/promotions/se-october-2026-public.json': `${JSON.stringify(publicReviewed, null, 2)}\n`,
    'data/promotions/se-silicone-head-public.json': `${JSON.stringify(publicHeads, null, 2)}\n`
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [file, content] of Object.entries(publicPromotionOutputs())) {
    if (process.argv.includes('--check')) {
      if (!fs.existsSync(path.join(root, file)) || read(file) !== content) throw new Error(`Regenerate public promotion data: ${file}`);
    } else fs.writeFileSync(path.join(root, file), content);
  }
}
