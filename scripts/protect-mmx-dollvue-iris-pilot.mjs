import fs from 'node:fs/promises';
import sharp from 'sharp';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {createServer} from 'vite';

const root='data/exports/dol312-mmx-nov10/pilot-monica';
const digest=b=>createHash('sha256').update(b).digest('hex');
assert.equal(digest(await fs.readFile(`${root}/source-original.jpg`)),'00e6dddf69209bda5cb512ecc0ae821ca760fcada43e3da7f61d30e2023db911','Manual mask requires the exact reviewed source bytes');
assert.equal(digest(await fs.readFile(`${root}/output-raw.webp`)),'9d18f0ae6acf2d9ba0b8270c1f25922bb2c63f68cf404bfac9e94f93003751f4','Candidate coordinates require exact reviewed generated bytes');
const source=await sharp(`${root}/source-original.jpg`).removeAlpha().raw().toBuffer({resolveWithObject:true});
const normalized=await sharp(`${root}/output-raw.webp`).resize(source.info.width,source.info.height).removeAlpha().raw().toBuffer({resolveWithObject:true});
assert(source.info.width===1000&&source.info.height===1500,'This manually reviewed pilot mask is source-specific; never reuse by product label');
const w=source.info.width,h=source.info.height;
// Manually inspected iris locations in this exact source and failed generated
// candidate, at the original 1000x1500 coordinate system. This is NOT an automatic
// mask generator or an all-product approval. Source face/body pixels are locked.
const eyes=[{target:[519.5,167.2],candidate:[514.8,166.0]},
 {target:[571.5,171.2],candidate:[567.0,169.0]}];
const out=Buffer.from(source.data),mask=Buffer.alloc(w*h);
let altered=0;
for(const eye of eyes){
 const [cx,cy]=eye.target,[gx,gy]=eye.candidate;
 for(let y=Math.floor(cy-5);y<=Math.ceil(cy+5);y++)for(let x=Math.floor(cx-7);x<=Math.ceil(cx+7);x++){
  const radius=Math.sqrt(((x-cx)/5.5)**2+((y-cy)/3.8)**2);
  if(radius>=1)continue;
  const i=(y*w+x)*3;
  const lum=(source.data[i]+source.data[i+1]+source.data[i+2])/3;
  // Preserve the original pupil and bright specular glints rather than copying
  // an eye from a different geometry. The selected region is iris pigment only.
  if(lum<45||lum>185)continue;
  const tx=Math.round(gx+x-cx),ty=Math.round(gy+y-cy),j=(ty*w+tx)*3;
  const alpha=Math.min(1,(1-radius)/0.22);
  mask[y*w+x]=Math.round(alpha*255);
  for(let c=0;c<3;c++)out[i+c]=Math.round(source.data[i+c]*(1-alpha)+normalized.data[j+c]*alpha);
 }
}
let outsideChangedPixels=0,insideChangedPixels=0;
for(let p=0;p<w*h;p++){
 const i=p*3,changed=out[i]!==source.data[i]||out[i+1]!==source.data[i+1]||out[i+2]!==source.data[i+2];
 if(changed){if(mask[p])insideChangedPixels++;else outsideChangedPixels++;}
}
assert.equal(outsideChangedPixels,0,'An unselected pixel changed');assert(insideChangedPixels>0,'No iris pigment change');
const outputPNG=await sharp(out,{raw:{width:w,height:h,channels:3}}).png().toBuffer();
await fs.writeFile(`${root}/output-iris-protected.png`,outputPNG);
await sharp(mask,{raw:{width:w,height:h,channels:1}}).png().toFile(`${root}/iris-only-mask.png`);
const server=await createServer({configFile:false,server:{middlewareMode:true},resolve:{alias:{'@':process.cwd()}},plugins:[{
 name:'private-node-server-marker',resolveId(id){if(id==='server-only')return '\0private-server-only';},load(id){if(id==='\0private-server-only')return 'export {};';}
}]});
try{
 const {brandDollVuePreview}=await server.ssrLoadModule('/lib/dollvue/branding.ts');
 const branded=await brandDollVuePreview(outputPNG,'mmx-monica-163a-silicone-companion-doll',[{group:'Eye Color',option:'Regular #1'}]);
 const meta=await sharp(branded).metadata();assert.equal(meta.width,w);
 const footer=await sharp(branded).extract({left:0,top:h,width:w,height:meta.height-h}).png().toBuffer();
 // The normal helper encodes WebP. Append its footer to the locked PNG instead
 // so JPEG/WebP recompression cannot change protected source-photo pixels.
 const final=await sharp({create:{width:w,height:meta.height,channels:3,background:'#fff'}})
  .composite([{input:outputPNG,left:0,top:0},{input:footer,left:0,top:h}]).png().toBuffer();
 await fs.writeFile(`${root}/output-iris-protected-branded.png`,final);
 const check=await sharp(final).extract({left:0,top:0,width:w,height:h}).removeAlpha().raw().toBuffer();
 assert(check.equals(out),'Branded output changed protected photo pixels');
 for(const [bytes,name] of [[await fs.readFile(`${root}/source-original.jpg`),'source-iris-face.png'],[outputPNG,'protected-iris-face.png']]){
  await sharp(bytes).extract({left:400,top:65,width:260,height:270}).resize(520,540).png().toFile(`${root}/${name}`);
 }
 await sharp({create:{width:1040,height:540,channels:3,background:'#fff'}})
  .composite([{input:`${root}/source-iris-face.png`,left:0,top:0},{input:`${root}/protected-iris-face.png`,left:520,top:0}]).png().toFile(`${root}/protected-iris-face-comparison.png`);
 const report={at:new Date().toISOString(),status:'PRIVATE_SOURCE_SPECIFIC_LOCALITY_PROBE',
  rawGenerationResult:'FAILED_SAME_DOLL_FIDELITY; unselected face/body drift',
  mitigation:'Transfer only the generated iris pigment within a manually reviewed exact-source mask. All unselected pixels remain original.',
  providerMaskClaim:false,sourceDimensions:{width:w,height:h},manualSourceMask:true,
  selectedFeature:'Eye Color Regular #1 only. Hairstyle output discarded.',
  insideChangedPixels,outsideChangedPixels,originalPixelEqualityOutsideMask:true,
  brandedPhotoEqualsProtectedComposite:true,outputSHA256:digest(outputPNG),maskSHA256:digest(mask),
  photoEncoding:'PNG, lossless',footer:'Existing DollVue branded footer appended outside photograph',
  newProviderCalls:0,totalProviderCalls:1,visualReviewComplete:true,visualReviewResult:'Iris pigment visible; source geometry preserved exactly. Limited source-specific locality probe only.',
  limitations:['One source-specific hand-reviewed iris mask, not automatic SKU coverage.',
   'Exact factory eye-reference equivalence and final visual review still required.',
   'No hair, makeup, head-swap or other feature fidelity approval follows from iris locality.',
   'A general mask preparation/validation pipeline is needed before public behavior changes.'],
  productionMutations:0,emails:0,customerUsageWrites:0,cartWrites:0};
 await fs.writeFile(`${root}/protected-iris-locality-proof.json`,JSON.stringify(report,null,2));
 console.log(JSON.stringify({insideChangedPixels,outsideChangedPixels,protectedPhotoPixels:true,output:`${root}/output-iris-protected-branded.png`}));
}finally{await server.close();}
