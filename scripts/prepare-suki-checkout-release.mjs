import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
const [runtimePath,chargesPath,marketsPath]=process.argv.slice(2);
assert(runtimePath&&chargesPath&&marketsPath,'Pass runtime, charge and market evidence paths');
const runtime=JSON.parse(await fs.readFile(runtimePath,'utf8'));
const charges=JSON.parse(await fs.readFile(chargesPath,'utf8'));
const availability=JSON.parse(await fs.readFile(marketsPath,'utf8'));
assert.equal(runtime.product.id,'gid://shopify/Product/10630580273336');
assert.equal(runtime.presets.length,3);
assert.equal(charges.parentVariantId,runtime.product.variants[0].id);
assert(availability.markets.every(m=>m.available===m.total&&m.total===new Set(charges.bindings.map(b=>b.merchandiseId)).size));
assert(Date.now()-Date.parse(availability.at)<86400000);
const hash=value=>crypto.createHash('sha256').update(value).digest('hex');
const canonical=value=>Array.isArray(value)?value.map(canonical):value&&typeof value==='object'?Object.fromEntries(Object.entries(value).filter(([,v])=>v!==undefined).sort(([a],[b])=>a.localeCompare(b)).map(([k,v])=>[k,canonical(v)])):value;
const cartFile=new URL('../lib/cart/evidence/named-upgrades-release.json',import.meta.url);
const templateFile=new URL('../lib/customization/evidence/template-release.json',import.meta.url);
const cart=JSON.parse(await fs.readFile(cartFile,'utf8'));
const templates=JSON.parse(await fs.readFile(templateFile,'utf8'));
assert.equal(cart.approval.payloadHash,hash(JSON.stringify(cart.payload)));
for(const approval of Object.values(templates.approvals))assert.equal(approval.payloadHash,hash(JSON.stringify(canonical(templates.payload))));
const group='irontech-silicone-166v2-s20-ros-max';
cart.payload.parents[charges.parentVariantId]=group;
cart.payload.groups[group]=charges.bindings.map(({status,origin,...b})=>b);
cart.payload.releaseId='named-upgrades-2026-10-03-suki';
const evidenceRef='docs/catalog/suki-release-2026-10-03.md',reviewedAt=new Date().toISOString();
cart.approval={payloadHash:hash(JSON.stringify(cart.payload)),evidenceRef,reviewedAt};
const bindingKey=hash(runtime.definition.tag);
templates.payload.entries=templates.payload.entries.filter(e=>e.productId!==runtime.product.id);
templates.payload.entries.push({productId:runtime.product.id,handle:runtime.product.handle,tag:runtime.definition.tag,bindingKey,runtimeHash:runtime.runtimeHash});
templates.payload.expectedProductIds=[...new Set([...templates.payload.expectedProductIds,runtime.product.id])];
templates.payload.bindings[bindingKey]={...runtime.definition,signature:`sha256:${hash(runtime.definition.signature)}`};
templates.payload.releaseId='presets-2026-10-03-suki';
templates.payload.sourceSnapshotHash=hash(JSON.stringify({previous:templates.payload.sourceSnapshotHash,product:runtime.product}));
const payloadHash=hash(JSON.stringify(canonical(templates.payload)));
templates.approvals=Object.fromEntries(Object.keys(templates.approvals).map(gate=>[gate,{reviewedBy:'Codex: incremental Suki source/menu and named-charge preflight; prior entries preserved',reviewedAt,evidenceRef,payloadHash}]));
await fs.writeFile(cartFile,JSON.stringify(cart)+'\n');
await fs.writeFile(templateFile,JSON.stringify(templates)+'\n');
console.log(JSON.stringify({product:runtime.product.id,presets:runtime.presets.map(p=>({label:p.label,total:p.totalPrice})),bindings:charges.bindings.length,priorProductsPreserved:true}));
